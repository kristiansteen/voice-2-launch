export function quickPlaybookFilename(processName, variant = 'to-be') {
  const slug = (processName || 'process').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'process';
  return `${slug}-${variant}-quick-playbook.md`;
}

const norm = s => (s || '').trim().toLowerCase();

export function buildQuickPlaybook({ parsed, processName, processDescription, metrics, systemMap = {}, variant = 'to-be', lang = 'en', businessCase = null, businessCaseInputs = {} } = {}) {
  if (!parsed) return null;
  const T = TXT[lang] || TXT.en;
  const fill = T.fill;
  const p = {
    roles: [], events: [], activities: [], gateways: [], sequence_flows: [],
    ...parsed,
  };
  const name = processName || p.process_name || processDescription?.process_name || 'Process';
  const steps = buildSteps(p);
  const stepNo = Object.fromEntries(steps.map(s => [s.id, s.step]));
  const stepLabel = Object.fromEntries(steps.map(s => [s.id, s.label]));
  const descByName = Object.fromEntries((processDescription?.steps || []).map(s => [norm(s.name), s.description]));
  const metricById = Object.fromEntries((metrics?.activities || []).map(a => [a.id, a]));
  const sys = id => (systemMap && systemMap[id]) || '';

  const L = [];
  L.push(`# ${name}`, '', `**${T.playbook}** · ${T.variant[variant] || variant}`, '');

  L.push(`## ${T.howTo}`, '');
  T.howToSteps.forEach((s, i) => L.push(`${i + 1}. ${s}`));
  L.push('');

  L.push(`## ${T.project}`, '');
  L.push(`- **${T.name}:** ${name}`);
  L.push(`- **${T.purpose}:** ${processDescription?.overview || fill(T.purpose.toLowerCase())}`);
  if (processDescription?.scope) L.push(`- **${T.scope}:** ${processDescription.scope}`);
  const oneLine = s => String(s).replace(/\s*\n+\s*/g, ' ').trim();
  if (businessCaseInputs?.problem) L.push(`- **${T.problem}:** ${oneLine(businessCaseInputs.problem)}`);
  if (businessCaseInputs?.target) L.push(`- **${T.target}:** ${oneLine(businessCaseInputs.target)}`);
  L.push(`- **${T.business}:** ${businessCaseSummary(businessCase, lang) || fill(T.fillCase)}`);
  const roleNames = p.roles.map(r => r.name).filter(Boolean);
  if (roleNames.length) L.push(`- **${T.roles}:** ${roleNames.join(', ')}`);
  L.push('');

  L.push(`## ${T.connectors}`, '');
  const systems = {};
  steps.forEach(s => { if (s.type === 'activity' && sys(s.id)) (systems[sys(s.id)] ||= []).push(s.step); });
  if (Object.keys(systems).length) {
    Object.entries(systems).forEach(([sy, nos]) => L.push(`- **${sy}** — ${T.usedIn} ${nos.join(', ')}`));
  } else {
    L.push(T.noSystems);
  }
  L.push('');

  L.push(`## ${T.setup}`, '');
  T.setupItems.forEach(s => L.push(`- [ ] ${s}`));
  L.push('');

  L.push(`## ${T.steps}`, '', T.stepsIntro, '');
  const humanSteps = [];
  steps.forEach(s => {
    if (s.type === 'start') { L.push(`### ${T.step} ${s.step} — ${T.trigger}: ${s.label}`, ''); return; }
    if (s.type === 'end') { L.push(`### ${T.step} ${s.step} — ${T.ends}: ${s.label}`, ''); return; }
    if (s.type === 'intermediate') { L.push(`### ${T.step} ${s.step} — ${s.label}`, ''); return; }
    if (s.type === 'gateway') {
      L.push(`### ${T.step} ${s.step} — ${T.decision}: ${s.label}`, '');
      s.branches.forEach((b, i) => {
        const cond = b.condition || (i === s.branches.length - 1 && i > 0 ? T.otherwise : fill('condition'));
        L.push(`- ${T.ifBranch} **${cond}** → ${T.step} ${stepNo[b.to] ?? '?'}: ${stepLabel[b.to] || b.to}`);
      });
      L.push('');
      return;
    }
    // activity
    const human = APPROVAL.test(s.label || '');
    if (human) humanSteps.push(s);
    const m = metricById[s.id];
    L.push(`### ${T.step} ${s.step} — ${s.label}`, '');
    L.push(`- ${human ? T.kindHuman : T.kindAgent}`);
    if (human) L.push(`- **${T.reviewer}:** ${s.role || fill(T.reviewer.toLowerCase())}`);
    else if (s.role) L.push(`- **${T.performer}:** ${s.role}`);
    L.push(`- **${T.system}:** ${sys(s.id) || fill(T.fillSystem)}`);
    if (m && m.duration_value) L.push(`- **${T.time}:** ${formatMinutes(toMinutes(m.duration_value, m.duration_unit))}`);
    L.push(`- **${T.instructions}:** ${descByName[norm(s.label)] || fill(T.fillDesc)}`);
    L.push(`- **${T.inputs}:** ${fill(T.fillIO)}`);
    L.push('');
  });

  const exc = processDescription?.exceptions || [];
  if (exc.length) {
    L.push(`## ${T.exceptions}`, '');
    exc.forEach(e => L.push(`- ${e}`));
    L.push('');
  }

  L.push(`## ${T.tests}`, '');
  const end = steps.find(s => s.type === 'end');
  L.push(`- [ ] ${T.testHappy} “${end?.label || T.ends}”`);
  steps.filter(s => s.type === 'gateway').forEach(g => L.push(`- [ ] ${T.testBranch} “${g.label}”`));
  if (humanSteps.length) L.push(`- [ ] ${T.testHuman}`);
  L.push('', '---', `_${T.generated}_`, '');
  return L.join('\n');
}
